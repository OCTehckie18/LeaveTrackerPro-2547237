"""Document storage behind a tiny interface: local folder (dev/Docker) or S3 API (Supabase Storage)."""

import re
from pathlib import Path
from typing import Protocol

from app.core.config import Settings
from app.domain.errors import ServiceUnavailable

_KEY = re.compile(r"^docs/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")


class BlobStore(Protocol):
    def put(self, key: str, data: bytes, content_type: str) -> None: ...
    def get(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...


def _check_key(key: str) -> str:
    if not _KEY.match(key):  # keys are generated by us; this stops any path trickery outright
        raise ValueError("invalid storage key")
    return key


class LocalBlobStore:
    def __init__(self, root: str) -> None:
        self.root = Path(root).resolve()
        (self.root / "docs").mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        return self.root / _check_key(key)

    def put(self, key: str, data: bytes, content_type: str) -> None:
        self._path(key).write_bytes(data)

    def get(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except FileNotFoundError as exc:
            raise ServiceUnavailable("That file is temporarily unavailable.") from exc

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


class S3BlobStore:
    def __init__(self, settings: Settings) -> None:
        import boto3
        from botocore.config import Config

        assert settings.storage_s3_access_key_id and settings.storage_s3_secret_access_key
        self.bucket = settings.storage_bucket
        self.client = boto3.client(
            "s3",
            endpoint_url=settings.storage_s3_endpoint,
            region_name=settings.storage_s3_region,
            aws_access_key_id=settings.storage_s3_access_key_id.get_secret_value(),
            aws_secret_access_key=settings.storage_s3_secret_access_key.get_secret_value(),
            config=Config(signature_version="s3v4", retries={"max_attempts": 2}),
        )

    def put(self, key: str, data: bytes, content_type: str) -> None:
        self.client.put_object(
            Bucket=self.bucket, Key=_check_key(key), Body=data, ContentType=content_type
        )

    def get(self, key: str) -> bytes:
        try:
            obj = self.client.get_object(Bucket=self.bucket, Key=_check_key(key))
            return bytes(obj["Body"].read())
        except Exception as exc:
            raise ServiceUnavailable("That file is temporarily unavailable.") from exc

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=_check_key(key))


def build_blobstore(settings: Settings) -> BlobStore:
    if settings.storage_s3_endpoint:
        return S3BlobStore(settings)
    return LocalBlobStore(settings.local_storage_dir)
